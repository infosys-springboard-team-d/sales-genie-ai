from __future__ import annotations

import argparse
import csv
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import sklearn
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import cross_val_score, train_test_split
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT_DIR = ROOT / "resource" / "synthetic_scoring_prototype"
FEATURES = (
    "outreach_attempts",
    "email_reply",
    "meeting_booked",
    "need_confirmed",
    "decision_maker_contacted",
    "budget_confirmed",
    "proposal_requested",
)
LABEL = "won_within_90_days"
SEED = 20261104


def generate_synthetic_dataset(
    sample_count: int = 10_000, seed: int = SEED
) -> tuple[np.ndarray, np.ndarray]:
    if sample_count < 100:
        raise ValueError("sample_count must be at least 100.")

    rng = np.random.default_rng(seed)
    feature_columns = {
        "outreach_attempts": rng.integers(0, 8, size=sample_count),
        "email_reply": rng.integers(0, 2, size=sample_count),
        "meeting_booked": rng.integers(0, 2, size=sample_count),
        "need_confirmed": rng.integers(0, 2, size=sample_count),
        "decision_maker_contacted": rng.integers(0, 2, size=sample_count),
        "budget_confirmed": rng.integers(0, 2, size=sample_count),
        "proposal_requested": rng.integers(0, 2, size=sample_count),
    }
    features = np.column_stack([feature_columns[name] for name in FEATURES])

    attempts = feature_columns["outreach_attempts"]
    replied = feature_columns["email_reply"].astype(bool)
    meeting = feature_columns["meeting_booked"].astype(bool)
    need = feature_columns["need_confirmed"].astype(bool)
    decision_maker = feature_columns["decision_maker_contacted"].astype(bool)
    budget = feature_columns["budget_confirmed"].astype(bool)
    proposal = feature_columns["proposal_requested"].astype(bool)

    # Simulated outcomes are generated from this invented rule plus label noise.
    labels = (
        (meeting & (need | proposal))
        | (proposal & budget)
        | (replied & need & decision_maker & (attempts <= 5))
    ).astype(np.int8)
    noisy_rows = rng.random(sample_count) < 0.04
    labels[noisy_rows] = 1 - labels[noisy_rows]
    return features, labels


def write_synthetic_csv(
    path: Path, features: np.ndarray, labels: np.ndarray
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as output_file:
        writer = csv.writer(output_file)
        writer.writerow((*FEATURES, LABEL))
        for row, label in zip(features, labels, strict=True):
            writer.writerow((*map(int, row), int(label)))


def train_and_evaluate(
    sample_count: int = 10_000, seed: int = SEED
) -> tuple[RandomForestClassifier, dict[str, Any], np.ndarray, np.ndarray]:
    features, labels = generate_synthetic_dataset(sample_count, seed)
    x_train, x_test, y_train, y_test = train_test_split(
        features,
        labels,
        test_size=0.2,
        random_state=seed,
        stratify=labels,
    )
    model = RandomForestClassifier(
        n_estimators=250,
        max_depth=8,
        min_samples_leaf=8,
        class_weight="balanced",
        random_state=seed,
        n_jobs=-1,
    )
    cv_scores = cross_val_score(
        model, x_train, y_train, cv=5, scoring="accuracy", n_jobs=-1
    )
    model.fit(x_train, y_train)
    predictions = model.predict(x_test)
    matrix = confusion_matrix(y_test, predictions, labels=[0, 1])
    metrics: dict[str, Any] = {
        "evaluation_type": "synthetic_simulation_only",
        "milestone_2_acceptance_eligible": False,
        "positive_label_definition": (
            "Simulated Won within 90 days; labels are generated by an invented "
            "rule with 4% random label flips, not observed sales outcomes."
        ),
        "sample_count": int(sample_count),
        "train_count": int(len(y_train)),
        "holdout_count": int(len(y_test)),
        "seed": int(seed),
        "feature_names": list(FEATURES),
        "label_name": LABEL,
        "model": "RandomForestClassifier",
        "model_parameters": model.get_params(),
        "scikit_learn_version": sklearn.__version__,
        "class_prevalence": {
            "simulated_won_rate": float(np.mean(labels)),
            "holdout_simulated_won_rate": float(np.mean(y_test)),
        },
        "train_only_five_fold_accuracy_mean": float(cv_scores.mean()),
        "train_only_five_fold_accuracy_std": float(cv_scores.std()),
        "holdout_metrics": {
            "accuracy": float(accuracy_score(y_test, predictions)),
            "precision": float(precision_score(y_test, predictions, zero_division=0)),
            "recall": float(recall_score(y_test, predictions, zero_division=0)),
            "f1": float(f1_score(y_test, predictions, zero_division=0)),
            "confusion_matrix_labels_0_1": matrix.tolist(),
            "majority_class_baseline_accuracy": float(
                max(np.mean(y_test == 0), np.mean(y_test == 1))
            ),
        },
        "interpretation": (
            "Holdout results measure recovery of the synthetic label generator "
            "only. They do not measure real lead conversion or verify the "
            "Milestone 2 85% scoring-accuracy target. Do not use this model "
            "for real prospects or production scoring."
        ),
    }
    return model, metrics, features, labels


def run(output_dir: Path, sample_count: int, seed: int) -> dict[str, Any]:
    model, metrics, features, labels = train_and_evaluate(sample_count, seed)
    output_dir.mkdir(parents=True, exist_ok=True)
    write_synthetic_csv(output_dir / "synthetic_lead_outcomes.csv", features, labels)
    joblib.dump(model, output_dir / "synthetic_scoring_model.joblib")
    metrics["generated_at_utc"] = datetime.now(timezone.utc).isoformat()
    metrics["dataset_file"] = "synthetic_lead_outcomes.csv"
    metrics["model_file"] = "synthetic_scoring_model.joblib"
    (output_dir / "evaluation.json").write_text(
        json.dumps(metrics, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return metrics


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Train an isolated scoring prototype on synthetic labels. "
            "This cannot verify Milestone 2 scoring accuracy."
        )
    )
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--samples", type=int, default=10_000)
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()
    report = run(args.output_dir, args.samples, args.seed)
    holdout = report["holdout_metrics"]
    print(f"Synthetic holdout accuracy: {holdout['accuracy']:.3f}")
    print(f"Majority-class baseline: {holdout['majority_class_baseline_accuracy']:.3f}")
    print(f"Milestone 2 acceptance eligible: {report['milestone_2_acceptance_eligible']}")
    print(f"Results: {args.output_dir / 'evaluation.json'}")


if __name__ == "__main__":
    main()
